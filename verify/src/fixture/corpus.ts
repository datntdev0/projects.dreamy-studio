import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { prototypeNovelCorpus, prototypeNovels } from "../paths.ts";
import { packDirectory } from "./novels.ts";

const CJK = /[぀-ヿ㐀-䶿一-鿿豈-﫿가-힯]/u;
const ALNUM = /[\p{L}\p{N}]/u;
const HEADER = "/* Generated by verify/src/fixture/corpus.ts from ../assets/novel/<pack>/ on every `pnpm fixture` and `pnpm baseline`. Do not edit. */";

interface Manifest {
  readonly chapters: readonly { readonly file: string; readonly title: string }[];
}

interface CorpusChapter {
  readonly title: string;
  readonly words: number;
  readonly paras: readonly string[];
}

export function wordCount(text: string): number {
  let words = 0;
  let inToken = false;
  for (const character of text) {
    if (CJK.test(character)) {
      words += 1;
      inToken = false;
    } else if (/\s/u.test(character)) {
      inToken = false;
    } else if (ALNUM.test(character) && !inToken) {
      words += 1;
      inToken = true;
    }
  }
  return words;
}

function paragraphsOf(text: string): string[] {
  return text.split(/\r?\n/u).map((line) => line.trim()).filter((line) => line !== "");
}

async function readChapters(pack: string): Promise<CorpusChapter[]> {
  const manifest = JSON.parse(await readFile(join(packDirectory(pack), "manifest.json"), "utf8")) as Manifest;
  const chapters: CorpusChapter[] = [];
  for (const entry of manifest.chapters) {
    const paras = paragraphsOf(await readFile(join(packDirectory(pack), entry.file), "utf8"));
    chapters.push({ title: entry.title, words: wordCount(paras.join("\n")), paras });
  }
  return chapters;
}

async function packs(): Promise<string[]> {
  const found = await readdir(prototypeNovels, { withFileTypes: true });
  const folders = found.filter((item) => item.isDirectory()).map((item) => item.name).sort();
  return folders.filter((folder) => existsSync(join(packDirectory(folder), "manifest.json")));
}

export async function writeCorpus(): Promise<boolean> {
  const corpus: Record<string, { chapters: CorpusChapter[] }> = {};
  for (const pack of await packs()) {
    corpus[pack] = { chapters: await readChapters(pack) };
  }
  const source = [HEADER, `window.NVC = ${JSON.stringify(corpus, null, 1)};`, ""].join("\n");
  const current = existsSync(prototypeNovelCorpus) ? await readFile(prototypeNovelCorpus, "utf8") : null;
  if (current === source) {
    return false;
  }
  await writeFile(prototypeNovelCorpus, source);
  return true;
}
